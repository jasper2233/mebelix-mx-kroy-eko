def error_field_label(loc) -> str:
    """Xato joylashuvi → odam o'qiydigan maydon nomi (joriy tilda): `parts.0.length` → «Детали №1 › Длина»."""
    items = list(loc or ())
    if items and str(items[0]) in _LOC_SKIP:
        items = items[1:]
    idx = 1 if LANG.get() == "uz" else 0
    out: list[str] = []
    for it in items:
        if isinstance(it, int) or (isinstance(it, str) and it.isdigit()):
            n = f"№{int(it) + 1}"
            out[-1:] = [f"{out[-1]} {n}"] if out else [n]
            continue
        k = str(it)
        if k.startswith(("function-after[", "function-before[", "function-wrap[", "union[", "tagged-union[")):
            continue                                       # pydantic ichki qadami (validator nomi) — foydalanuvchiga keraksiz
        pair = FIELD_LABELS.get(k)
        out.append(pair[idx] if pair else k)
    return " › ".join(out)


def error_text(err: dict) -> str:
    """Bitta pydantic xatosi → qisqa sabab (joriy til: ru/uz)."""
    t = str(err.get("type", ""))
    ctx = err.get("ctx") or {}

    def c(k):
        return _fmt_num(ctx.get(k, ""))
    if t == "missing":
        return _("val_missing")
    if t == "greater_than_equal":
        return _("val_ge", v=c("ge"))
    if t == "greater_than":
        return _("val_gt", v=c("gt"))
    if t == "less_than_equal":
        return _("val_le", v=c("le"))
    if t == "less_than":
        return _("val_lt", v=c("lt"))
    if t in ("int_parsing", "int_type", "int_from_float", "int_parsing_size"):
        return _("val_int")
    if t in ("float_parsing", "float_type"):
        return _("val_number")
    if t == "finite_number":
        return _("val_finite")
    if t == "string_type":
        return _("val_str")
    if t in ("bool_parsing", "bool_type"):
        return _("val_bool")
    if t == "string_too_short":
        return _("val_str_short", v=c("min_length"))
    if t == "string_too_long":
        return _("val_str_long", v=c("max_length"))
    if t in ("enum", "literal_error"):
        exp = ctx.get("expected") or ""
        return _("val_choice") + (f" ({exp})" if exp else "")
    if t.startswith(("date", "time")) or t in ("datetime_parsing", "datetime_type"):
        return _("val_date")
    if t == "json_invalid":
        return _("val_json")
    if t in ("list_type", "tuple_type", "set_type"):
        return _("val_list")
    if t in ("dict_type", "model_type", "model_attributes_type"):
        return _("val_dict")
    if t == "too_short":
        return _("val_list_short", v=c("min_length"))
    if t == "too_long":
        return _("val_list_long", v=c("max_length"))
    if t == "extra_forbidden":
        return _("val_extra")
    if t == "multiple_of":
        return _("val_multiple", v=c("multiple_of"))
    if t in ("uuid_parsing", "uuid_type"):
        return _("val_id")
    if t in ("value_error", "assertion_error"):
        msg = str(err.get("msg", ""))
        for pre in ("Value error, ", "Assertion failed, "):
            if msg.startswith(pre):
                msg = msg[len(pre):]
        return msg or _("val_generic")
    return _("val_generic")


def format_errors(errors, limit: int = 3) -> str:
    """Xatolar ro'yxati → bitta o'qiladigan matn: «maydon: sabab; maydon: sabab»."""
    out = []
    for er in list(errors)[:limit]:
        f = error_field_label(er.get("loc")) or _("val_body")
        out.append(f"{f}: {error_text(er)}")
    more = len(list(errors)) - limit
    return "; ".join(out) + (f" (+{more})" if more > 0 else "")
